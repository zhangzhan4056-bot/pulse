def _inject_css():
    """注入 tooltip CSS（每个页面只需调用一次）"""
    if not st.session_state.get("_tooltip_css_injected"):
        st.session_state["_tooltip_css_injected"] = True
        st.markdown(_TOOLTIP_CSS, unsafe_allow_html=True)


def tip_icon(text: str) -> str:
    """生成带 CSS tooltip 的 ? 图标 HTML

    Args:
        text: tooltip 内容（支持 markdown 格式，会自动转为纯文本）

    Returns:
        可直接嵌入 st.markdown(unsafe_allow_html=True) 的 HTML 字符串
    """
    _inject_css()
    # 去掉 markdown 格式标记，转为纯文本
    import re
    plain = re.sub(r'\*\*(.+?)\*\*', r'\1', text)  # **bold** → bold
    plain = re.sub(r'\*(.+?)\*', r'\1', plain)      # *italic* → italic
    # 转义 HTML 特殊字符
    safe = plain.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return (
        f'<span class="tip-trigger">?'
        f'<span class="tip-text">{safe}</span>'
        f'</span>'
    )


def _tip(title: str, formula: str, range_: str = "", note: str = "") -> str:
    """构造 tooltip 文本"""
    parts = [f"**{title}**", formula]
    if range_:
        parts.append(f"范围: {range_}")
    if note:
        parts.append(note)
    return "  \n".join(parts)


